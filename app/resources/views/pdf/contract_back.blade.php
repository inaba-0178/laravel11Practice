    <div class="title">自動車売買注文書 特約条項（約款）</div>

    {{-- ===== 第1条 ===== --}}
    <div class="section">
        <div class="article-title">第1条（契約の成立時期）</div>
        <div class="article-body">
            <p>本契約は、次の各号に定める日のいずれか早期の日に成立するものとします。</p>
            <p class="indent">（1）販売店が買主の依頼に基づき、車両の登録（名義変更）手続きを行った日。</p>
            <p class="indent">（2）販売店が買主の依頼に基づき、車両の点検・整備、またはオプション等の取付に着手した日。</p>
            <p class="indent">（3）車両が買主に引き渡された（納車された）日。</p>
        </div>
    </div>

    {{-- ===== 第2条 ===== --}}
    <div class="section">
        <div class="article-title">第2条（契約の解除・キャンセル）</div>
        <div class="article-body">
            <p>1. 前条に定める「契約成立前」であれば、買主は無償で本契約を解除することができます。</p>
            <p>2. 「契約成立後」の買主都合によるキャンセルは原則として認められません。ただし、販売店がやむを得ないと認めた場合に限り、販売店がそれまでに要した実費（登録費用、整備費用、部品代等）および所定の違約金を支払うことで契約を解除できるものとします。</p>
        </div>
    </div>

    {{-- ===== 第3条 ===== --}}
    <div class="section">
        <div class="article-title">第3条（必要書類の提出および代金支払期限）</div>
        <div class="article-body">
            <p>1. 買主は、販売店が指定する期日までに、登録手続きに必要な書類（普通車：印鑑登録証明書・委任状、軽自動車：住民票等）を速やかに提出するものとします。</p>
            <p>2. 買主は、頭金および購入代金（またはローン手続き）を、販売店と合意した支払期日までに完了させるものとします。</p>
        </div>
    </div>

    {{-- ===== 第4条 ===== --}}
    <div class="section">
        <div class="article-title">第4条（瑕疵担保責任・車両の保証）</div>
        <div class="article-body">
            <p>1. 車両の引き渡し後、車両に隠れた欠陥（瑕疵）が発見された場合、表面に「保証付き」の記載がある車両については、その保証規約の範囲内において無償修理を行います。</p>
            <p>2. 表面に「現状販売（保証なし）」と記載されている車両については、引き渡し後の故障、不具合、摩耗等について、販売店は一切の修理・交換・返品の責任を負わないものとします。</p>
        </div>
    </div>

    {{-- ===== 第5条 ===== --}}
    <div class="section">
        <div class="article-title">第5条（契約の解除と所有権留保）</div>
        <div class="article-body">
            <p>1. 買主が正当な理由なく代金の支払いを怠った場合、または必要書類を提出しない場合、販売店は催告のうえ本契約を解除し、違約金を請求できるものとします。</p>
            <p>2. 分割払い（オートローン）を利用する場合、代金が完済されるまでは、車両の所有権は販売店またはクレジット会社に留保されるものとします。</p>
        </div>
    </div>
